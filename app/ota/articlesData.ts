export type ArticleBlock =
  | { type: 'p'; text: string }
  | { type: 'h3'; text: string }
  | { type: 'ul'; items: { bold?: string; text: string }[] }
  | { type: 'ol'; items: { bold?: string; text: string }[] }
  | {
      type: 'box'
      variant: 'criteria' | 'steps'
      title: string
      text?: string
      items?: string[]
      ordered?: boolean
    }
  | {
      type: 'table'
      caption?: string
      headers: string[]
      rows: string[][]
    }
  | {
      type: 'hub'
      center: string
      spokes: string[]
      caption: string
    }
  | {
      type: 'matrix'
      title: string
      xAxisLeft: string
      xAxisRight: string
      cells: [MatrixCell, MatrixCell, MatrixCell, MatrixCell]
      caption?: string
    }
  | {
      type: 'pyramid'
      title: string
      layers: { label: string; sub?: string }[]
      caption?: string
    }
  | {
      type: 'flow'
      title: string
      direction?: 'vertical' | 'horizontal'
      steps: { step: string; title: string; desc: string }[]
      caption?: string
    }
  | {
      type: 'revenueBars'
      title: string
      caption: string
    }

